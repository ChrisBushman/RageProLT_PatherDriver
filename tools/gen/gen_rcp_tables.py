#!/usr/bin/env python3
"""Generates common/rage_rcp_tables.h: reciprocal seed tables for common/rage_vmath.h.
Tables hold 1/m for m = 1 + i/N (left edge of the interval), as Q1.31 unsigned (value * 2^31, so 1.0 = 0x80000000)."""
import sys
def tab(n, bits_ok):
    out = []
    for i in range(n + 1):                        # n+1 entries so interpolation can read i+1
        m = 1.0 + i / n
        out.append(min(int(round((1.0 / m) * (1 << 31))), 0x80000000))
    return out
t8 = tab(256, 32)
t11 = tab(2048, 32)
with open(sys.argv[1], 'w') as f:
    f.write('/* GENERATED by tools/gen/gen_rcp_tables.py - do not edit.  Q1.31 reciprocal seeds 1/(1+i/N). */\n#ifndef RAGE_RCP_TABLES_H\n#define RAGE_RCP_TABLES_H\n#include <stdint.h>\n')
    f.write('static const uint32_t rage_rcp8[257] = {\n')
    for i in range(0, 257, 6): f.write('    ' + ', '.join('0x%08xu' % v for v in t8[i:i+6]) + ',\n')
    f.write('};\n')
    f.write('/* 11-bit seeds, Q0.16 of the Q1.31 value >> 15 (16 bits): */\nstatic const uint16_t rage_rcp11[2049] = {\n')
    for i in range(0, 2049, 10): f.write('    ' + ', '.join('0x%04x' % min(0xffff, v >> 15) for v in t11[i:i+10]) + ',\n')
    f.write('};\n#endif\n')
