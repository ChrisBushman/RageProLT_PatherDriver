#!/usr/bin/env python3
"""gen_table.py TRACE OUT.h [OTHER_TRACE ...]
Build the Rage LT Pro init replay table from a biosrun hardware trace of the card's own ROM init + VBE mode 0110 taken with BIOS_TSTAMP=1
(line prefix "@<us>", used for the delays) and the exact-offset hardware trace (" o=0x.." on CHIP-WR, used for the byte offsets).  Any further
traces given are checked for an identical write sequence (offset, size, value): the ROM's setup must not depend on the boot.  Entries: PCI command-register write, chip writes (offset, size, value), the two
accesses biosrun performs outside the ROM trace (BIOS_POKE 8c:40000000 right after the INT42 init stop, BUS_CNTL bit 27 at the end), and a
delay (us) before an entry where the ROM waited on the 8254 timer.  Only the writes are replayed: no read in the trace gates anything
(no status-poll loops: checked), reads are side-effect free."""
import re, sys
ts_rows = []
for ln in open(sys.argv[1], errors='replace'):
    m = re.match(r'@(\d+) (CHIP-WR|CHIP-RD|CFGRD|CFGWR|INT42|IN|OUT) ?(.*)', ln)
    if not m: continue
    ts_rows.append((int(m.group(1)), m.group(2), m.group(3).split()))
o_writes = []
for ln in open(sys.argv[1], errors='replace'):
    p = re.sub(r'^@\d+ ', '', ln).split()
    if p and p[0] == 'CHIP-WR': o_writes.append(p)
ENT = []          # (kind, off, size, val, delay_us)
pend = 0; prev_t = None; pit_seen = False; wi = 0; mism = 0
for t, k, r in ts_rows:
    if k in ('IN', 'OUT'):
        if r and len(r) > 1 and r[1] in ('0x40', '0x43'): pit_seen = True
        continue
    gap = (t - prev_t) if prev_t is not None else 0
    prev_t = t
    if pit_seen and gap >= 50: pend += gap
    pit_seen = False
    if k == 'CHIP-WR':
        o = o_writes[wi]; wi += 1
        reg, size, val = int(r[0], 16), int(r[2], 16), int(r[3], 16)
        if (int(o[1], 16), int(o[3], 16), int(o[4], 16)) != (reg, size, val): mism += 1
        off = int(o[5].split('=')[1], 16)
        ENT.append(('W', off, size, val, pend)); pend = 0
    elif k == 'CFGWR':
        ENT.append(('C', int(r[0], 16), int(r[1], 16), int(r[2], 16), pend)); pend = 0
    elif k == 'INT42':
        ENT.append(('W', 0x8c, 4, 0x40000000, pend)); pend = 0     # BIOS_POKE=8c:40000000 (applied by biosrun right after the init stop)
ENT.append(('RMW_BUSCNTL27', 0xa0, 4, 1 << 27, 0))                # biosrun platform fix-up, applied after init and before the mode set? (see note)
assert wi == len(o_writes) and mism == 0, (wi, len(o_writes), mism)
print("entries", len(ENT), "writes", wi, "total delay %.3f s" % (sum(e[4] for e in ENT) / 1e6), "max delay %d us" % max(e[4] for e in ENT))
for other in sys.argv[3:]:
    seq = []
    for ln in open(other, errors='replace'):
        p = re.sub(r'^@\d+ ', '', ln).split()
        if p and p[0] == 'CHIP-WR': seq.append((int(p[1], 16), int(p[3], 16), int(p[4], 16)))
    mine = [(int(o[1], 16), int(o[3], 16), int(o[4], 16)) for o in o_writes]
    assert seq == mine, other + ': write sequence differs'
    print('same write sequence as', other)
with open(sys.argv[2], 'w') as f:
    f.write("/* GENERATED by tools/rageinit/gen_table.py from biosrun traces of the card's own option ROM (init + VBE mode 0110) -- do not edit. */\n")
    f.write("enum { RI_WRITE = 0, RI_CFGWRITE = 1, RI_SETBITS = 2 };\n")
    f.write("struct rage_init_op { unsigned char kind, size; unsigned short off; unsigned int val; unsigned int delay_us; };\n")
    f.write("static const struct rage_init_op kRageInit[] = {\n")
    for kind, off, size, val, d in ENT:
        kk = {'W': 'RI_WRITE', 'C': 'RI_CFGWRITE', 'RMW_BUSCNTL27': 'RI_SETBITS'}[kind]
        f.write("  { %s, %d, 0x%x, 0x%x, %d },\n" % (kk, size, off, val, d))
    f.write("};\n")
